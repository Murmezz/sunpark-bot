async function applyConfig(env) {
  if (Date.now() - cfgAt < 30000) return;
  try {
    await env.DB.prepare("CREATE TABLE IF NOT EXISTS manager_states (user_id INTEGER PRIMARY KEY, action TEXT NOT NULL)").run();
    const { results } = await env.DB.prepare("SELECT key, value FROM config").all();
    const cfg = Object.fromEntries(results.map((r) => [r.key, r.value]));
    if (!cfg.menu) {
      const v = JSON.stringify({
        MENU: DEFAULT_MENU, MENU_SECTIONS: DEFAULT_MENU_SECTIONS, INFO_TEXT: DEFAULT_INFO_TEXT,
      });
      await env.DB.prepare("INSERT OR IGNORE INTO config (key, value) VALUES ('menu', ?)").bind(v).run();
      cfg.menu = v;
    }
    const m = JSON.parse(cfg.menu);
    if (!m.MENU || !m.MENU_SECTIONS || !m.INFO_TEXT) throw new Error("menu JSON incomplete");
    MENU = m.MENU;
    MENU_SECTIONS = m.MENU_SECTIONS;
    INFO_TEXT = m.INFO_TEXT;
    PHONE = cfg.phone || "+76767676767";
    MANAGERS_CFG = cfg.manager_ids || "";
    cfgAt = Date.now();
  } catch (e) {
    console.error("config", e.message);
  }
}

// ---------- Telegram API ----------
async function tg(env, method, params) {
  const r = await fetch(`https://api.telegram.org/bot${env.BOT_TOKEN}/${method}`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify(params),
  });
  const data = await r.json();
  if (!data.ok) {
    console.error("Telegram API error", {
      method,
      http_status: r.status,
      description: data.description || "unknown error",
      error_code: data.error_code || null,
    });
    throw new Error(`${method}: ${data.description || "Telegram API error"}`);
  }
  return data.result;
}
