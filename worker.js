async function onMessage(env, msg) {
  const text = msg.text;
  if (!text || !msg.from || msg.chat.type !== "private") return;
  const uid = msg.from.id;
  const mgr = isManager(env, uid);

  if (text.startsWith("/start")) {
    await send(env, uid, homeText(), homeKeyboard());
    await send(env, uid, "Нижняя кнопка «🏠 Главное меню» всегда вернёт вас сюда.", persistentKeyboard(env, uid));
    return;
  }
  if (text === "🏠 Главное меню") return void (await send(env, uid, homeText(), homeKeyboard()));
  if (text === "👀 Как гость" && mgr)
    return void (await send(env, uid, "👀 <b>Режим просмотра как гость</b>", homeKeyboard()));
  if (text === "⚙️ Админ-панель" && mgr)
    return void (await send(env, uid, await adminPanelText(env), adminPanelKeyboard()));
  if ((text === "👀 Как гость" || text === "⚙️ Админ-панель") && !mgr) return;

  // Менеджер -> гостю, с которым он сейчас работает.
  if (mgr) {
    const t = await env.DB.prepare(
      "SELECT guest_id FROM tickets WHERE manager_id=? AND status='active' ORDER BY claimed_at DESC, number DESC LIMIT 1"
    ).bind(uid).first();
    if (t) {
      try {
        await send(env, t.guest_id, `👨‍💼 <b>Менеджер:</b>\n${esc(text)}`);
        await send(env, uid, "✅ Сообщение отправлено гостю.");
      } catch (e) {
        console.error(e);
        await send(env, uid, "⚠️ Не удалось отправить сообщение гостю.");
      }
      return;
    }
  }

  const own = await env.DB.prepare(
    "SELECT * FROM tickets WHERE guest_id=? AND status IN ('draft','waiting','active') ORDER BY number DESC LIMIT 1"
  ).bind(uid).first();
  if (!own) return;

  if (own.status === "active") {
    // Гость -> назначенному менеджеру.
    try {
      await send(env, own.manager_id,
        `💬 <b>Обращение #${own.number}</b>\n👤 ${guestLabel(msg.from)}\n\n${esc(text)}`,
        managerMessageKeyboard(uid));
      await send(env, uid, "📨 Сообщение отправлено менеджеру.");
    } catch (e) {
      console.error(e);
      await send(env, uid, "⚠️ Не удалось отправить сообщение менеджеру. Попробуйте ещё раз.");
    }
    return;
  }

  // Гость -> всем менеджерам, пока обращение никто не взял.
  const body =
    `🆕 <b>Новое обращение #${own.number}</b>\n\n👤 <b>Гость:</b> ${guestLabel(msg.from)}\n` +
    `🆔 <b>ID:</b> <code>${uid}</code>\n\n💬 <b>Сообщение:</b>\n${esc(text)}`;
  await Promise.all([...managerSet(env)].map((m) =>
    send(env, m, body, claimKeyboard(uid)).catch((e) => console.error("manager", m, e.message))));
  await env.DB.prepare("UPDATE tickets SET status='waiting' WHERE number=?").bind(own.number).run();
  await send(env, uid,
    "📨 Спасибо! Ваше сообщение отправлено менеджерам SUNPARK.\n\n" +
    "Как только один из менеджеров возьмёт обращение, мы продолжим общение здесь.");
}

// ---------- Кнопки ----------
async function onCallback(env, cb) {
  const data = cb.data || "";
  const uid = cb.from.id;
  const msg = cb.message;
  if (!msg) return void (await answer(env, cb.id));
  const mgr = isManager(env, uid);
  const done = () => answer(env, cb.id);

  if (data === "noop") return void (await done());
  if (data === "back") { await edit(env, msg, homeText(), homeKeyboard()); return void (await done()); }
  if (data === "home:menu") {
    await edit(env, msg, "🍽 <b>Основное меню SUNPARK</b>\n\nВыберите раздел:", mainMenuKeyboard());
    return void (await done());
  }
  if (data === "home:banquet") { await edit(env, msg, banquetText(), banquetStartKeyboard()); return void (await done()); }
  if (data === "banquet:list") {
    await edit(env, msg, "🎉 <b>Банкетное меню</b>\n\nВыберите позицию:", categoryKeyboard("banquet"));
    return void (await done());
  }
  if (data === "info") {
    await edit(env, msg, INFO_TEXT, kb([[btn("🏠 На главную", "back")]]));
    return void (await done());
  }
  if (data.startsWith("cat:")) {
    const key = data.slice(4);
    if (!MENU[key]) return void (await answer(env, cb.id, "Раздел не найден", true));
    const cat = MENU[key];
    await edit(env, msg,
      `<b>${cat.emoji} ${cat.title}</b>\n\nНажмите на позицию, чтобы посмотреть состав.\n\nВнизу можно вернуться к разделам или на главную:`,
      categoryKeyboard(key));
    return void (await done());
  }
  if (data.startsWith("item:")) {
    const parts = data.split(":");
    const index = Number(parts[2]);
    if (parts.length !== 3 || !Number.isInteger(index)) return void (await answer(env, cb.id, "Позиция не найдена", true));
    if (!MENU[parts[1]]) return void (await answer(env, cb.id, "Раздел не найден", true));
    await edit(env, msg, formatItem(parts[1], index), itemBackKeyboard(parts[1]));
    return void (await done());
  }

  // --- Обращение гостя ---
  if (data === "manager:start") {
    await edit(env, msg, contactChoiceText(), contactChoiceKeyboard());
    return void (await done());
  }
  if (data === "manager:call") {
    await edit(env, msg, callText(env), callKeyboard());
    return void (await done());
  }
  if (data === "manager:write") {
    const active = await env.DB.prepare("SELECT 1 FROM tickets WHERE guest_id=? AND status='active'").bind(uid).first();
    if (active) return void (await answer(env, cb.id, "Ваше обращение уже отправлено менеджерам."));
    const open = await env.DB.prepare("SELECT 1 FROM tickets WHERE guest_id=? AND status IN ('draft','waiting')").bind(uid).first();
    if (!open) await env.DB.prepare("INSERT INTO tickets (guest_id, status) VALUES (?, 'draft')").bind(uid).run();
    await edit(env, msg, banquetContactText() + "\n\n<b>✍️ Напишите сообщение следующим сообщением.</b>", managerPromptKeyboard());
    return void (await done());
  }
  if (data === "manager:cancel") {
    await env.DB.prepare("DELETE FROM tickets WHERE guest_id=? AND status IN ('draft','waiting')").bind(uid).run();
    await edit(env, msg, banquetText(), banquetStartKeyboard());
    return void (await done());
  }

  // --- Менеджер ---
  if (data.startsWith("claim:")) {
    if (!mgr) return void (await answer(env, cb.id, "Эта кнопка доступна только менеджерам.", true));
    const guestId = Number(data.slice(6));
    const res = await env.DB.prepare(
      "UPDATE tickets SET status='active', manager_id=?, claimed_at=datetime('now') WHERE guest_id=? AND status='waiting'"
    ).bind(uid, guestId).run();
    if (!res.meta.changes) {
      const taken = await env.DB.prepare("SELECT 1 FROM tickets WHERE guest_id=? AND status='active'").bind(guestId).first();
      await answer(env, cb.id, taken ? "Обращение уже взял другой менеджер." : "Это обращение уже недоступно.", true);
      return void (await clearMarkup(env, msg));
    }
    const t = await env.DB.prepare(
      "SELECT number FROM tickets WHERE guest_id=? AND manager_id=? AND status='active' ORDER BY number DESC"
    ).bind(guestId, uid).first();
    await tg(env, "editMessageReplyMarkup", {
      chat_id: msg.chat.id, message_id: msg.message_id, reply_markup: managerMessageKeyboard(guestId),
    }).catch(() => {});
    await send(env, msg.chat.id,
      `✅ <b>Обращение #${t.number} взято вами.</b>\n\nТеперь сообщения этого гостя будут приходить вам, а ваши ответы — гостю.`);
    await send(env, guestId,
      "👨‍💼 <b>Вашим обращением занимается менеджер SUNPARK.</b>\n\nМожете продолжать писать сообщения прямо здесь.")
      .catch((e) => console.error("guest notify", e.message));
    return void (await answer(env, cb.id, "Обращение закреплено за вами."));
  }
  if (data.startsWith("close:")) {
    if (!mgr) return void (await answer(env, cb.id, "Эта кнопка доступна только менеджерам.", true));
    const guestId = Number(data.slice(6));
    const t = await env.DB.prepare(
      "SELECT number FROM tickets WHERE guest_id=? AND manager_id=? AND status='active'"
    ).bind(guestId, uid).first();
    if (!t) return void (await answer(env, cb.id, "Это обращение вам не назначено.", true));
    await env.DB.prepare("UPDATE tickets SET status='closed', closed_at=datetime('now') WHERE number=?").bind(t.number).run();
    await clearMarkup(env, msg);
    await send(env, msg.chat.id, `✅ Обращение #${t.number} завершено.`);
    await send(env, guestId,
      "✅ <b>Обращение завершено.</b>\n\nЕсли у вас появится новый вопрос по банкету, просто нажмите «💬 Связаться с менеджером» снова.")
      .catch((e) => console.error("guest notify", e.message));
    return void (await done());
  }

  // --- Админ-панель ---
  if (data.startsWith("admin:")) {
    if (!mgr) return void (await answer(env, cb.id, "Доступ запрещён.", true));
    const what = data.slice(6);
    if (what === "panel") await edit(env, msg, await adminPanelText(env), adminPanelKeyboard());
    else if (what === "active") await edit(env, msg, await adminActiveText(env), adminBackKeyboard());
    else if (what === "closed") await edit(env, msg, await adminClosedText(env), adminBackKeyboard());
    else if (what === "guest") await edit(env, msg, homeText(), homeKeyboard());
    else if (what === "stats") {
      const { active, waiting, closed } = await counts(env);
      await edit(env, msg,
        `📊 <b>Статистика</b>\n\n🟡 Активных: <b>${active}</b>\n🆕 Ожидают: <b>${waiting}</b>\n` +
        `✅ Завершено: <b>${closed}</b>\n👨‍💼 Менеджеров в белом списке: <b>${managerSet(env).size}</b>`,
        adminBackKeyboard());
    }
    return void (await done());
  }
  await done();
}

// ---------- Вход ----------
export default {
  async fetch(request, env) {
    if (request.method !== "POST") return new Response("SUNPARK bot is running");
    // Telegram webhook requests are accepted without a mandatory secret-token check.
    // The bot token remains stored as a Cloudflare secret and is never exposed to clients.
    let update;
    try { update = await request.json(); } catch { return new Response("bad request", { status: 400 }); }
    try {
      await applyConfig(env);
      if (update.message) await onMessage(env, update.message);
      else if (update.callback_query) await onCallback(env, update.callback_query);
    } catch (e) {
      console.error(e);
    }
    return new Response("ok");
  },
};